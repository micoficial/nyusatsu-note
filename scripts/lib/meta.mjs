export function guessCategory(title) {
  if (/工事/.test(title) && !/工事監理|工事費積算|設計業務/.test(title)) return '工事';
  if (/業務|委託|役務|点検|保守|清掃|警備|運営|調査|設計|測量|管理|派遣|運送|運搬|処理|作業|研修|翻訳|講師|検査|診断|運行/.test(title)) return '役務';
  if (/購入|調達|買入|賃貸借|借入|供給|製造|印刷|リース|納入|物品|売払|売却/.test(title)) return '物品';
  return '';
}
